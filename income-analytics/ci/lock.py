"""Resolve reviewed Windows/Python 3.14 wheels, then write a pip hash-checked lock.

Maintenance only: installation consumes the committed lock, never this resolver.
"""

import argparse
import json
import platform
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runtime", action="store_true")
    args = parser.parse_args()
    if sys.version_info[:2] != (3, 14) or platform.system() != "Windows":
        raise SystemExit("Lock generation requires Windows x64 and Python 3.14.")
    if platform.machine().lower() not in {"amd64", "x86_64"}:
        raise SystemExit("Lock generation requires x64.")
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    requirements = [
        *project["project"]["dependencies"],
        *(project["project"]["optional-dependencies"]["dev"] if not args.runtime else []),
        *project["build-system"]["requires"],
        "pip==26.2.1",
    ]
    with tempfile.TemporaryDirectory(prefix="income-ci-lock-") as temp:
        report = Path(temp) / "resolution.json"
        subprocess.run(
            [
                sys.executable,
                "-m",
                "pip",
                "--isolated",
                "install",
                "--dry-run",
                "--ignore-installed",
                "--only-binary=:all:",
                "--index-url",
                "https://pypi.org/simple",
                "--constraint",
                str(ROOT / "ci/requirements-seed.txt"),
                "--report",
                str(report),
                *requirements,
            ],
            check=True,
        )
        resolved = json.loads(report.read_text(encoding="utf-8"))
    lines = [
        "# Generated by ci/lock.py; Windows x64 / CPython 3.14; PyPI wheels only.",
        "# All direct and transitive dependencies are pinned to the selected wheel SHA-256.",
        "# Regenerate only in a reviewed dependency change. Do not run resolver in CI.",
    ]
    for item in sorted(resolved["install"], key=lambda row: row["metadata"]["name"].lower()):
        download = item["download_info"]
        if not download["url"].startswith("https://files.pythonhosted.org/"):
            raise SystemExit("Unexpected package origin in resolution.")
        if not download["url"].endswith(".whl"):
            raise SystemExit("Only wheels are accepted.")
        digest = download["archive_info"]["hashes"]["sha256"]
        metadata = item["metadata"]
        lines.append(f"{metadata['name']}=={metadata['version']} --hash=sha256:{digest}")
    name = "runtime-windows-py314.lock" if args.runtime else "requirements-windows-py314.lock"
    destination = ROOT / "ci" / name
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Locked {len(resolved['install'])} wheels.")


if __name__ == "__main__":
    main()
