import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
let logouts = 0, focused = false, fail = false;
const label = {textContent:"Sair da conta"};
const button = {disabled:false, handlers:{}, querySelector:()=>label, addEventListener(name,fn){this.handlers[name]=fn;}};
const status = {textContent:""};
const trigger = {focus(){focused=true;}};
const menu = {open:true, handlers:{}, querySelector(selector){return selector==="summary"?trigger:selector==="button"?button:status;}, addEventListener(name,fn){this.handlers[name]=fn;}, contains(target){return target===button;}};
const documentHandlers = {};
const context = vm.createContext({signOutDevice:async()=>{logouts++;if(fail)throw Error("offline");},document:{createElement:()=>menu,addEventListener:(name,fn)=>documentHandlers[name]=fn}});
vm.runInContext(fs.readFileSync("src/income_analytics/api/static/js/account-menu.js","utf8").replace(/^import .*;$/m,"").replace("export function","function"),context);
context.mountAccountMenu({append:()=>{}});
assert.ok(menu.innerHTML.includes("Sair da conta"));
menu.handlers.keydown({key:"Escape"});assert.equal(menu.open,false);assert.equal(focused,true);
menu.open=true;documentHandlers.pointerdown({target:{}});assert.equal(menu.open,false);
menu.open=true;documentHandlers.focusin({target:{}});assert.equal(menu.open,false);
fail=true;await button.handlers.click();assert.equal(button.disabled,false);assert.ok(status.textContent.includes("tente novamente"));
fail=false;await button.handlers.click();assert.equal(button.disabled,true);assert.equal(label.textContent,"Saindo…");
await button.handlers.click();assert.equal(logouts,2);
console.log("Account menu: Escape, outside click, focus departure, logout retry and duplicate protection passed.");
