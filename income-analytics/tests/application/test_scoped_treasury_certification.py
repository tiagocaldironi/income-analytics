"""Independent decimal examples with real dashboard rebuild, no pricing/ranking stub."""

from datetime import date
from decimal import Decimal as D

import pytest

from income_analytics.api.routers import dashboard
from income_analytics.application.portfolio_context import MAIN_PORTFOLIO_ID
from income_analytics.application.portfolio_session import PortfolioSession


@pytest.mark.parametrize("name", ["Tesouro Selic 2031", "Tesouro IPCA+ 2045",
                                  "Tesouro Prefixado 2032"])
def test_title_trade_projection_and_real_snapshot_reconcile(monkeypatch, name):
    session = PortfolioSession(portfolio_id=MAIN_PORTFOLIO_ID, persistent=False)
    monkeypatch.setattr(dashboard, "session", session)
    buy = dashboard.TreasuryTradeInput(
        event_type="BUY", ticker="TD-CERT", name=name, quantity="0.17",
        unit_price="1234.567891", gross_amount="209.88", effective_date=date(2026, 1, 1),
    )
    dashboard.create_treasury_trade(buy)
    dashboard.create_treasury_trade(dashboard.TreasuryTradeInput(
        event_type="SELL", ticker="TD-CERT", name=name, quantity="0.04",
        unit_price="1300.123456", gross_amount="52.00", effective_date=date(2026, 1, 2),
    ))
    session.update_market_price(
        ticker="TD-CERT", current_price=D("1500"), effective_date=date(2026, 1, 3)
    )
    original = tuple(session.history())
    position = session.project(as_of=date(2026, 1, 3)).positions[0]
    # Hand-derived independent expectations, not values generated by projectors:
    # 17/100 - 4/100 = 13/100 title; cost = 13 * 1234.567891 / 100.
    assert position.quantity.value == D("0.13")
    assert position.average_price.amount == D("1234.567891")
    assert position.cost.amount == D("160.49382583")
    assert position.realized_result.amount == D("2.62222260")
    assert position.market_value.amount == D("195")
    assert position.total_result.amount == D("37.12839677")
    snapshot = dashboard.rebuild_portfolio_dashboard_snapshot()
    holdings = snapshot["holdings"]
    assert D(str(holdings["portfolio_market_value"])) == D("195")
    assert len(holdings["classes"]) == len(holdings["display_groups"]) == 1
    assert holdings["classes"][0]["asset_class"] == "FIXED_INCOME"
    assert holdings["display_groups"][0]["asset_class"] == "TREASURY"
    assert tuple(session.history()) == original
